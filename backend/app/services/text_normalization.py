def normalize_multilingual_text(text: str) -> str:
    """Normalize compatibility forms, case, and supported Traditional Chinese."""

    return (
        unicodedata.normalize("NFKC", text)
        .casefold()
        .translate(TRADITIONAL_TO_SIMPLIFIED)
    )
