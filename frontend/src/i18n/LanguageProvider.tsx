function toTraditional(source: string) {
  let output = source
  for (const [simplified, traditional] of Object.entries(traditionalPhraseOverrides)) {
    output = output.split(simplified).join(traditional)
  }
  return Array.from(output, (character) => traditionalCharacters[character] ?? character).join('')
}

type LanguageContextValue = {
  language: Language
  setLanguage: (language: Language) => void
  t: (source: string) => string
}

const LanguageContext = createContext<LanguageContextValue | null>(null)

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => {
    const stored = window.localStorage.getItem(STORAGE_KEY)
    return stored === 'zh-CN' || stored === 'zh-TW' || stored === 'en' ? stored : 'en'
  })

  const setLanguage = (nextLanguage: Language) => {
    window.localStorage.setItem(STORAGE_KEY, nextLanguage)
    setLanguageState(nextLanguage)
  }

  useEffect(() => {
    document.documentElement.lang = language
  }, [language])

  const value = useMemo<LanguageContextValue>(
    () => ({
      language,
      setLanguage,
      t: (source) => {
        if (language === 'en') return english[source] ?? source
        if (language === 'zh-TW') return toTraditional(source)
        return source
      },
    }),
    [language],
  )

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export function useLanguage() {
  const context = useContext(LanguageContext)
  if (!context) throw new Error('useLanguage must be used within LanguageProvider')
  return context
}
